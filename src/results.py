"""Single source of truth for measured numbers.

Every phase calls `record(section, values)`. Values are stored in results.json and
RESULTS.md is regenerated from it, so no number in the docs is ever typed by hand.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from typing import Any

from src.config import RESULTS_JSON, RESULTS_MD

SECTION_ORDER = [
    "ingestion",
    "dataset",
    "baseline",
    "clustering",
    "transformer",
    "comparison",
    "retrieval",
    "agent",
]

SECTION_TITLES = {
    "ingestion": "Ingestion and extraction",
    "dataset": "Labelled dataset",
    "baseline": "Classical baselines (TF-IDF)",
    "clustering": "Unsupervised analysis (TF-IDF → SVD → KMeans)",
    "transformer": "DistilBERT fine-tune",
    "comparison": "Baseline vs transformer (same test split)",
    "retrieval": "Retrieval evaluation",
    "agent": "Agent and adversarial refusals",
}


def load() -> dict[str, Any]:
    if RESULTS_JSON.exists():
        return json.loads(RESULTS_JSON.read_text())
    return {}


def record(section: str, values: dict[str, Any]) -> None:
    if section not in SECTION_ORDER:
        raise ValueError(f"Unknown results section {section!r}; expected one of {SECTION_ORDER}")
    data = load()
    data[section] = {**values, "_recorded_at": datetime.now(UTC).isoformat(timespec="seconds")}
    RESULTS_JSON.write_text(json.dumps(data, indent=2, sort_keys=True, default=str) + "\n")
    render()


def update(section: str, values: dict[str, Any]) -> None:
    """Merge values into an existing section (e.g. re-evaluation keeps training time)."""
    existing = {k: v for k, v in load().get(section, {}).items() if not k.startswith("_")}
    record(section, {**existing, **values})


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def _render_value(key: str, value: Any) -> list[str]:
    """Render scalars as bullets, dict-of-dicts as tables, lists of dicts as tables."""
    if isinstance(value, dict) and value and all(isinstance(v, dict) for v in value.values()):
        cols: list[str] = []
        for row in value.values():
            for c in row:
                if c not in cols:
                    cols.append(c)
        lines = [f"**{key}**", "", "| | " + " | ".join(cols) + " |", "|---" * (len(cols) + 1) + "|"]
        for rk, row in value.items():
            lines.append(f"| {rk} | " + " | ".join(_fmt(row.get(c, "")) for c in cols) + " |")
        return lines + [""]
    if isinstance(value, list) and value and all(isinstance(v, dict) for v in value):
        cols = list(value[0].keys())
        lines = [f"**{key}**", "", "| " + " | ".join(cols) + " |", "|---" * len(cols) + "|"]
        for row in value:
            lines.append(
                "| " + " | ".join(_fmt(row.get(c, "")).replace("\n", " ") for c in cols) + " |"
            )
        return lines + [""]
    if isinstance(value, dict):
        return [f"- **{key}**: " + ", ".join(f"{k}={_fmt(v)}" for k, v in value.items())]
    return [f"- **{key}**: {_fmt(value)}"]


def render() -> None:
    data = load()
    out = [
        "# RESULTS",
        "",
        "Generated by `src/results.py` from `results.json`. Do not edit by hand —",
        "re-run the phase that produced a number to change it.",
        "",
    ]
    for section in SECTION_ORDER:
        out.append(f"## {SECTION_TITLES[section]}")
        out.append("")
        if section not in data:
            out.append("_Not yet measured._")
            out.append("")
            continue
        values = data[section]
        recorded = values.get("_recorded_at", "")
        for key, value in values.items():
            if key.startswith("_"):
                continue
            out.extend(_render_value(key, value))
        out.append("")
        out.append(f"_Recorded {recorded}._")
        out.append("")
    RESULTS_MD.write_text("\n".join(out))


if __name__ == "__main__":
    render()
    print(RESULTS_MD.read_text())
